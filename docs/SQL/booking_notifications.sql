-- FEATURE: booking emails cannot record whether they were sent, and the cancel or reschedule link in a visitor's email cannot find their meeting, so booking a meeting fails outright
-- RUN AFTER docs/SQL/booking_setup.sql
--
-- booking_notifications.sql
-- Booking calendar, slice 4 of 6 (SC-912): the emails, the add-to-calendar
-- file, and the visitor's private cancel/reschedule link.
--
-- Adds to public.bookings:
--   manage_token       a long random secret, one per booking. The visitor's
--                      email links to /api/public/booking/manage with it; it is
--                      the only thing that lets a visitor with no login cancel
--                      or move THEIR meeting. Unique, so a token names exactly
--                      one booking. Generated by lib/bookingStore.js.
--   visitor_time_zone  the visitor's own zone ("Europe/London"), read from their
--                      browser when they book, so their emails show their time
--   notify_status      how the LATEST round of emails went: 'sent' (both sides
--                      emailed) or 'failed' (at least one was not). NULL means
--                      no email was ever attempted (a booking made before this
--                      file ran). Shown on the Booking Manager.
--   notify_error       what went wrong, in plain words, when notify_status is
--                      'failed'
--   notified_at        when that round of emails was attempted
--   rescheduled_at     when the visitor last moved the meeting; also what makes
--                      a moved meeting's calendar file replace the old one
--
-- No new table, so no tenant columns and no RLS change: bookings already has
-- both tenant columns and RLS on (booking_setup.sql).
--
-- Idempotent: every statement is `if not exists`, so running the file twice
-- changes nothing.

alter table public.bookings add column if not exists manage_token text;
alter table public.bookings add column if not exists visitor_time_zone text;
alter table public.bookings add column if not exists notify_status text check (notify_status in ('sent', 'failed'));
alter table public.bookings add column if not exists notify_error text;
alter table public.bookings add column if not exists notified_at timestamptz;
alter table public.bookings add column if not exists rescheduled_at timestamptz;

create unique index if not exists idx_bookings_manage_token
  on public.bookings (manage_token);
